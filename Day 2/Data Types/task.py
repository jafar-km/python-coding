# Subscripting- pulling out a particular element from a string.
print("Hello"[4])

# String
print("123" + "345")

# Integer= Whole number(both positive and negative without decimal places.)
print(123 + 345)

# Large integers
print(123_456_789)

# Float = Floating Point Number (decimal)
print(3.1459)

# Boolean  = has two values
print(True)
print(False)